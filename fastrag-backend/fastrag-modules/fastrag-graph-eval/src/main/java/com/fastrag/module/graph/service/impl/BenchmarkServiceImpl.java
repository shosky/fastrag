package com.fastrag.module.graph.service.impl;

import cn.hutool.json.JSONUtil;
import com.baomidou.mybatisplus.core.conditions.query.LambdaQueryWrapper;
import com.fastrag.module.graph.entity.KbBenchmark;
import com.fastrag.module.graph.entity.KbBenchmarkQuestion;
import com.fastrag.module.graph.mapper.KbBenchmarkMapper;
import com.fastrag.module.graph.mapper.KbBenchmarkQuestionMapper;
import com.fastrag.module.graph.model.BenchmarkConfig;
import com.fastrag.module.graph.model.BenchmarkCreateForm;
import com.fastrag.module.graph.service.BenchmarkService;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;
import org.springframework.transaction.support.TransactionTemplate;

import java.util.ArrayList;
import java.util.List;

/**
 * 基准测试服务实现
 *
 * <p>支持：
 * <ul>
 *   <li>手动创建基准（空基准，后续上传 JSONL 或手动添加问题）</li>
 *   <li>LLM 自动生成基准问题（支持 vector/graph 两种模式）</li>
 *   <li>JSONL 文件解析导入</li>
 * </ul>
 *
 * <p>LLM 自动生成使用 {@link BenchmarkGenerationHelper} 异步执行，
 * 确保基准记录创建后立即返回，不会因 LLM 调用阻塞。
 */
@Slf4j
@Service
@RequiredArgsConstructor
public class BenchmarkServiceImpl implements BenchmarkService {

    private final KbBenchmarkMapper mapper;
    private final KbBenchmarkQuestionMapper questionMapper;
    private final TransactionTemplate transactionTemplate;
    private final BenchmarkGenerationHelper generationHelper;

    @Override
    public List<KbBenchmark> list(String kbId) {
        return mapper.selectList(new LambdaQueryWrapper<KbBenchmark>()
                .eq(KbBenchmark::getKbId, kbId)
                .orderByDesc(KbBenchmark::getCreatedAt));
    }

    @Override
    public KbBenchmark getDetail(String kbId, String id) {
        return mapper.selectById(id);
    }

    @Override
    public List<KbBenchmarkQuestion> listQuestions(String kbId, String benchmarkId) {
        return questionMapper.selectList(
                new LambdaQueryWrapper<KbBenchmarkQuestion>()
                        .eq(KbBenchmarkQuestion::getBenchmarkId, benchmarkId)
                        .orderByAsc(KbBenchmarkQuestion::getQuestionIndex));
    }

    @Override
    public KbBenchmark create(String kbId, BenchmarkCreateForm form) {
        KbBenchmark b = new KbBenchmark();
        b.setKbId(kbId);
        b.setName(form.getName());
        b.setDescription(form.getDescription());
        b.setQuestionCount(form.getQuestionCount() != null ? form.getQuestionCount() : 0);
        b.setIsAutoGenerated(0);
        b.setHasGoldChunks(0);
        b.setHasGoldAnswer(0);
        mapper.insert(b);
        return b;
    }

    // ==================== 自动生成 ====================

    @Override
    public KbBenchmark generate(String kbId, BenchmarkConfig config) {
        KbBenchmark b = new KbBenchmark();
        b.setKbId(kbId);
        b.setName(config.getName());
        b.setDescription(config.getDescription());
        b.setIsAutoGenerated(1);
        int questionCount = config.getQuestionCount() != null ? config.getQuestionCount() : 10;
        b.setQuestionCount(questionCount);

        String buildMethod = config.getBuildMethod() != null ? config.getBuildMethod() : "vector";
        b.setHasGoldChunks(1);
        b.setHasGoldAnswer(1);
        mapper.insert(b);

        // 异步生成问题：通过独立 Bean 确保 @Async 通过代理生效
        generationHelper.generateQuestions(b.getId(), kbId, questionCount, buildMethod, config);
        return b;
    }

    // ==================== JSONL 导入 ====================

    /**
     * 从 JSONL 内容中解析基准问题并导入
     *
     * <p>JSONL 每行格式：
     * <pre>
     * {"question": "问题文本", "goldChunks": ["fileId_chunk_0"], "goldAnswer": "标准答案"}
     * </pre>
     *
     * @param benchmarkId 目标基准 ID
     * @param jsonlContent JSONL 文本内容
     */
    public void importFromJsonl(String benchmarkId, String jsonlContent) {
        if (jsonlContent == null || jsonlContent.isBlank()) return;

        String[] lines = jsonlContent.split("\\n");
        List<KbBenchmarkQuestion> entities = new ArrayList<>();
        for (String line : lines) {
            line = line.trim();
            if (line.isEmpty()) continue;

            try {
                com.fasterxml.jackson.databind.JsonNode node =
                        new com.fasterxml.jackson.databind.ObjectMapper().readTree(line);
                String question = node.path("question").asText(null);
                if (question == null || question.isBlank()) continue;

                KbBenchmarkQuestion q = new KbBenchmarkQuestion();
                q.setBenchmarkId(benchmarkId);
                q.setQuestionIndex(entities.size());
                q.setQuestion(question);
                q.setGoldAnswer(node.path("goldAnswer").asText(null));

                com.fasterxml.jackson.databind.JsonNode goldChunksNode = node.path("goldChunks");
                if (goldChunksNode.isArray()) {
                    List<String> chunks = new ArrayList<>();
                    goldChunksNode.forEach(c -> chunks.add(c.asText()));
                    q.setGoldChunks(JSONUtil.toJsonStr(chunks));
                }

                entities.add(q);
            } catch (Exception e) {
                log.warn("[Benchmark] Failed to parse JSONL line: {}", line.substring(0, Math.min(50, line.length())));
            }
        }

        // 事务：批量插入 + 更新基准计数
        if (!entities.isEmpty()) {
            transactionTemplate.executeWithoutResult(status -> {
                for (KbBenchmarkQuestion q : entities) {
                    questionMapper.insert(q);
                }
                KbBenchmark benchmark = mapper.selectById(benchmarkId);
                if (benchmark != null) {
                    benchmark.setQuestionCount(benchmark.getQuestionCount() + entities.size());
                    benchmark.setHasGoldAnswer(1);
                    mapper.updateById(benchmark);
                }
            });
        }

        log.info("[Benchmark] Imported {} questions from JSONL for benchmark: {}", entities.size(), benchmarkId);
    }

    @Override
    public void delete(String kbId, String id) {
        questionMapper.delete(new LambdaQueryWrapper<KbBenchmarkQuestion>()
                .eq(KbBenchmarkQuestion::getBenchmarkId, id));
        mapper.deleteById(id);
    }
}
